-- Databricks notebook source
-- 10_create_tables: creates every warehouse table in workspace.dw and the audit tables
-- Owner: Ar. Run AFTER the schemas exist (workspace.dw, workspace.audit).

-- COMMAND ----------

-- Drop facts first: a dimension can't be replaced while a fact's foreign key points to it
DROP TABLE IF EXISTS workspace.dw.fact_event_loss;
DROP TABLE IF EXISTS workspace.dw.fact_state_year;

-- COMMAND ----------

CREATE SCHEMA IF NOT EXISTS workspace.dw;
CREATE SCHEMA IF NOT EXISTS workspace.audit;

-- COMMAND ----------

-- Dimensions
CREATE OR REPLACE TABLE workspace.dw.dim_date (
  date_key INT NOT NULL, full_date DATE, day_of_month INT, month_number INT,
  month_name STRING, calendar_quarter INT, calendar_year INT,
  au_financial_year INT, season STRING,
  CONSTRAINT pk_dim_date PRIMARY KEY (date_key));

-- COMMAND ----------

CREATE OR REPLACE TABLE workspace.dw.dim_location (
  location_key BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
  state_code STRING NOT NULL, state_name STRING, state_type STRING, country STRING,
  CONSTRAINT pk_dim_location PRIMARY KEY (location_key));

-- COMMAND ----------

CREATE OR REPLACE TABLE workspace.dw.dim_hazard (
  hazard_key BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
  hazard_group STRING NOT NULL, hazard_family STRING,
  CONSTRAINT pk_dim_hazard PRIMARY KEY (hazard_key));

-- COMMAND ----------

CREATE OR REPLACE TABLE workspace.dw.dim_event (
  event_key BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
  source_row_num INT, ica_cat_code STRING, event_name STRING,
  declaration_status STRING, state_original STRING, state_source STRING,
  multi_state_flag BOOLEAN, de_matched_flag BOOLEAN, de_source_id STRING,
  CONSTRAINT pk_dim_event PRIMARY KEY (event_key));

-- COMMAND ----------

-- Facts
CREATE OR REPLACE TABLE workspace.dw.fact_event_loss (
  event_key BIGINT NOT NULL, start_date_key INT, end_date_key INT,
  location_key BIGINT, hazard_key BIGINT,
  original_loss_aud DECIMAL(18,2), normalised_loss_2022_aud DECIMAL(18,2),
  total_claims INT, domestic_building_claims INT, domestic_content_claims INT,
  domestic_motor_claims INT, domestic_other_claims INT,
  commercial_property_claims INT, commercial_motor_claims INT,
  commercial_bi_claims INT, commercial_other_claims INT, commercial_crop_claims INT,
  duration_days INT, deaths INT, injuries INT, evacuated INT, homes_destroyed INT,
  run_id STRING,
  CONSTRAINT fk_fel_event FOREIGN KEY (event_key) REFERENCES workspace.dw.dim_event,
  CONSTRAINT fk_fel_start FOREIGN KEY (start_date_key) REFERENCES workspace.dw.dim_date,
  CONSTRAINT fk_fel_loc FOREIGN KEY (location_key) REFERENCES workspace.dw.dim_location,
  CONSTRAINT fk_fel_haz FOREIGN KEY (hazard_key) REFERENCES workspace.dw.dim_hazard);

-- COMMAND ----------

CREATE OR REPLACE TABLE workspace.dw.fact_state_year (
  location_key BIGINT NOT NULL, date_key INT NOT NULL,
  population BIGINT, population_year_used INT, population_imputed BOOLEAN,
  median_income_aud DECIMAL(12,2), income_year_used INT, income_imputed BOOLEAN,
  run_id STRING,
  CONSTRAINT fk_fsy_loc FOREIGN KEY (location_key) REFERENCES workspace.dw.dim_location,
  CONSTRAINT fk_fsy_date FOREIGN KEY (date_key) REFERENCES workspace.dw.dim_date);

-- COMMAND ----------

-- Audit
CREATE TABLE IF NOT EXISTS workspace.audit.etl_run_log (
  run_id STRING, step STRING, target_table STRING, source_rows BIGINT,
  loaded_rows BIGINT, rejected_rows BIGINT, status STRING, logged_at TIMESTAMP);
CREATE OR REPLACE TABLE workspace.audit.etl_rejects (
  run_id STRING, source_name STRING, source_row_num INT, rule_failed STRING,
  reason STRING, raw_record STRING, rejected_at TIMESTAMP);


